import os
import sys
import math
from PIL import Image

# MapID mapping based on standard modern WoW MapIDs
MAP_ID_MAPPING = {
    "EasternKingdoms_HighRes.png": 1415,
    "Kalimdor_HighRes.png": 13, # 1414 is the continent map, but 13 is the internal ID often used? Let's use 1414 for consistency.
    "Kalimdor_HighRes.png": 1414,
    "Outland_HighRes.png": 1945
}

TILE_SIZE = 256
OUTPUT_DIR = os.path.join("Interface", "AddOns", "GnomishPositioningSystem", "Tiles")
DATA_FILE = os.path.join("Interface", "AddOns", "GnomishPositioningSystem", "MapData.lua")

def process_maps():
    if not os.path.exists("maps"):
        print("Error: 'maps' directory not found.")
        return

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    map_data = {}

    for filename in os.listdir("maps"):
        if not filename.endswith(".png"):
            continue
            
        map_id = MAP_ID_MAPPING.get(filename)
        if not map_id:
            print(f"Skipping {filename}: No MapID mapping found.")
            continue

        print(f"Processing {filename} (MapID: {map_id})...")
        img_path = os.path.join("maps", filename)
        
        try:
            with Image.open(img_path) as img:
                width, height = img.size
                cols = math.ceil(width / TILE_SIZE)
                rows = math.ceil(height / TILE_SIZE)
                
                map_data[map_id] = {
                    "width": width,
                    "height": height,
                    "cols": cols,
                    "rows": rows,
                    "tileSize": TILE_SIZE
                }

                for r in range(rows):
                    for c in range(cols):
                        left = c * TILE_SIZE
                        top = r * TILE_SIZE
                        right = min(left + TILE_SIZE, width)
                        bottom = min(top + TILE_SIZE, height)
                        
                        tile = img.crop((left, top, right, bottom))
                        
                        # Pad tile to power of two if necessary (WoW requirement)
                        if tile.size != (TILE_SIZE, TILE_SIZE):
                            new_tile = Image.new("RGBA", (TILE_SIZE, TILE_SIZE), (0, 0, 0, 0))
                            new_tile.paste(tile, (0, 0))
                            tile = new_tile
                        
                        tile_filename = f"{map_id}_{r}_{c}.tga"
                        tile.save(os.path.join(OUTPUT_DIR, tile_filename))
                        
        except Exception as e:
            print(f"Error processing {filename}: {e}")

    write_lua_data(map_data)

def write_lua_data(map_data):
    with open(DATA_FILE, "w") as f:
        f.write("-- Generated by map_processor.py\n")
        f.write("local _, ns = ...\n")
        f.write("ns.MapData = {\n")
        for map_id, data in map_data.items():
            f.write(f"    [{map_id}] = {{\n")
            f.write(f"        width = {data['width']},\n")
            f.write(f"        height = {data['height']},\n")
            f.write(f"        cols = {data['cols']},\n")
            f.write(f"        rows = {data['rows']},\n")
            f.write(f"        tileSize = {data['tileSize']},\n")
            f.write("    },\n")
        f.write("}\n")
    print(f"Lua data written to {DATA_FILE}")

if __name__ == "__main__":
    process_maps()
