# S1 shells: the shells of every level as a city data addon (Shells_<name>.lua), and the baked pages as JPEG for
# the sandbox (the game would need them as BLP; not made yet).
# The data's path names the pages with .jpg (since 2026-10-24: the game test loads the sandbox's JPEG pages, the way GPS loads
# its overview images; BLP not made yet).
# Units: one per building unit (levels 0-3); the street layer's faces in 60-yd cells (each its own unit); blocks:
# one per 66.7-yd block of the ADT grid (level 4, every building and street of the block together). Per unit and
# level one string (GPS's 64-letter alphabet, as pb_city2.py):
#   n3 vertices, n3 faces, n1 index width w (2 or 3),
#   vertices: x, y, h as n3 each, (value - unit middle) * 32 + 131072,
#   faces: n1 corners (3 or 4), corners n<w> each (1-based, counter-clockwise seen from outside), n1 page,
#          texture coordinates n2 each per corner (u then v, 0..1 of the page * 4095; v down).
# Usage: [VAR=<variant>] [LEVELS=1,2,3] [JPG=<dir under the site>] python3 sh_tolua.py <addon dir> <sandbox site dir> [name]
# LEVELS: the unit levels written (others are empty strings: Shells.lua never draws them; minLevel says the finest).
import sys, os, json, pickle, numpy as np
from PIL import Image
OUT, SITE = sys.argv[1], sys.argv[2]; NAME = sys.argv[3] if len(sys.argv) > 3 else 'Stormwind'
B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
BLK = 1600 / 3 / 8
def enc(v, n):
    v = int(v); assert 0 <= v < 64 ** n, (v, n)
    return ''.join(B64[(v >> (6 * (n - 1 - i))) & 63] for i in range(n))
VAR = os.environ.get('VAR', ''); JPG = os.environ.get('JPG', 'shells')
LODS = (0, 1, 2, 3); USE = tuple(int(v) for v in os.environ.get('LEVELS', '0,1,2,3').split(','))
F = {L: pickle.load(open(f'sh_faces_{VAR}{L}.pkl', 'rb')) if L in USE + (4,) else {'faces': [], 'npages': 0} for L in LODS + (4,)}
stats = {L: {'faces': 0, 'quads': 0, 'verts': 0} for L in LODS + (4,)}; maxerr = [0.0]
def level_string(fl, c, L):
    vid, verts = {}, []
    for f in fl:
        for p in f['c']:
            q = tuple(np.round((p - c) * 32).astype(int))
            if q not in vid: vid[q] = len(verts) + 1; verts.append(q)
    w = 2 if len(verts) < 4096 else 3
    s = [enc(len(verts), 3), enc(len(fl), 3), enc(w, 1)]
    s += [enc(x + 131072, 3) for q in verts for x in q]
    for f in fl:
        s.append(enc(len(f['c']), 1))
        s += [enc(vid[tuple(np.round((p - c) * 32).astype(int))], w) for p in f['c']]
        s.append(enc(f['page'], 1))
        tc = np.clip(np.round(f['tc'] * 4095), 0, 4095).astype(int)
        s += [enc(x, 2) for x in tc.reshape(-1)]
        maxerr[0] = max(maxerr[0], float(np.abs(tc / 4095 - f['tc']).max()))
        stats[L]['quads'] += len(f['c']) == 4
    stats[L]['faces'] += len(fl); stats[L]['verts'] += len(verts)
    return ''.join(s)
def middle(fls):
    P = np.vstack([f['c'] for f in fls]); lo, hi = P.min(0), P.max(0); c = np.round((lo + hi) / 2 * 32) / 32
    return c, float(np.linalg.norm(P - c, axis=1).max())
def block_of(x, y): return (int(np.floor(x / BLK)) - 230) * 1000 + (int(np.floor(-y / BLK)) - 300)
# blocks (level 4)
blocks = {}
for f in F[4]['faces']: blocks.setdefault(-2 - f['unit'], []).append(f)
bidx, lua_blocks = {}, []
for bid, fl in sorted(blocks.items()):
    c, r = middle(fl); bidx[bid] = len(lua_blocks) + 1
    lua_blocks.append('{%.3f,%.3f,%.3f,%.1f,"%s"}' % (c[0], c[1], c[2], r, level_string(fl, c, 4)))
# units (levels 0-3)
def key_of(f):
    if f['unit'] >= 0: return ('b', f['unit'])
    c = f['c'].mean(0); return ('s', int(np.floor(c[0] / 60)), int(np.floor(c[1] / 60)))
units = {}
for L in LODS:
    for f in F[L]['faces']: units.setdefault(key_of(f), {l: [] for l in LODS})[L].append(f)
lua_units, orphans = [], 0
for k, per in sorted(units.items(), key=lambda kv: str(kv[0])):
    if not any(per[L] for L in LODS): continue
    c, r = middle([f for L in LODS for f in per[L]])
    b = bidx.get(block_of(c[0], c[1]), 0); orphans += b == 0
    lua_units.append('{%.3f,%.3f,%.3f,%.1f,%s,%d,%d}' % (c[0], c[1], c[2], r, ','.join('"%s"' % (level_string(per[L], c, L) if L in USE else '') for L in LODS), b, 1 if k[0] == 's' else 0))
os.makedirs(OUT, exist_ok=True)
addon = os.path.basename(OUT.rstrip('/'))
pages = [F[L]['npages'] for L in LODS + (4,)]
xs = [float(u.split(',')[0][1:]) for u in lua_units]; ys = [float(u.split(',')[1]) for u in lua_units]
head = ['-- Generated by sh_tolua.py (proof of concept S1, branch poc-shells): %s\'s buildings as closed shells with baked faces,' % NAME,
        '-- for GPS3D\'s Shells.lua. A unit: {x, y, h, radius, level 0, 1, 2, 3, its block, street (1) or building (0)}; a block (66.7 yd, every building and',
        '-- street in it together): {x, y, h, radius, level 4}. A level is one string (layout: sh_tolua.py), decoded when first',
        '-- drawn. Pictures: Shells\\L<level>_<page>.',
        'local _, ns = ...', 'ns.ShellData = ns.ShellData or {}', 'local U, B = {}, {}',
        'ns.ShellData[%s] = { map = 0, minLevel = %d, box = { %.1f, %.1f, %.1f, %.1f }, pages = { %s }, path = "Interface\\\\AddOns\\\\%s\\\\Shells\\\\L%%d_%%d.jpg", units = U, blocks = B }' % (
            json.dumps(NAME), min(USE), min(xs), max(xs), min(ys), max(ys), ', '.join(str(p) for p in pages), addon)]
body = ['do local u = { %s }; for k = 1, #u do U[#U + 1] = u[k] end end' % ', '.join(lua_units[i:i + 50]) for i in range(0, len(lua_units), 50)]
body += ['do local b = { %s }; for k = 1, #b do B[#B + 1] = b[k] end end' % ', '.join(lua_blocks[i:i + 50]) for i in range(0, len(lua_blocks), 50)]
open(os.path.join(OUT, f'Shells_{NAME}.lua'), 'w').write('\n'.join(head + body) + '\n')
os.makedirs(os.path.join(SITE, JPG), exist_ok=True)
jbytes = 0
for L in LODS + (4,):
    for i in range(F[L]['npages']):
        dst = os.path.join(SITE, JPG, f'L{L}_{i}.jpg')
        Image.open(f'shells_out{VAR}/L{L}_{i}.png').convert('RGB').save(dst, quality=88, optimize=True); jbytes += os.path.getsize(dst)
print(json.dumps({'units': len(lua_units), 'blocks': len(lua_blocks), 'units_without_block': orphans, 'lua_bytes': os.path.getsize(os.path.join(OUT, f'Shells_{NAME}.lua')),
                  'pages': pages, 'jpeg_bytes': jbytes, 'max_uv_err': maxerr[0], **{f'L{L}': stats[L] for L in LODS + (4,)}}))
