"""Turn gps-export.zip (made by scripts/browser_export.js in the MapExplorer page) into the addon's data.

Writes, relative to the repository root:
  Interface/AddOns/GnomishPositioningSystem/Data/MapTiles.lua   every map's tile -> minimap FileDataID, and its overview atlases
  Interface/AddOns/GnomishPositioningSystem/Overview/*.jpg      the overview atlases
  data/export.json                                              the raw export, for reference

Usage: python scripts/build_maptiles.py path/to/gps-export.zip [--tga]
  --tga  write the overview images as uncompressed TGA instead of JPEG (bigger; for clients that
         do not load JPEG from addons). Needs Pillow.
"""
import json
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADDON = os.path.join(ROOT, "Interface", "AddOns", "GnomishPositioningSystem")


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def fit_box(tiles):
    """Bounding box of the map's main land, leaving out small detached groups of tiles far from it
    (Kalimdor has a 3x3 test area in its corner). Groups join when tiles are within 2 tiles."""
    cells = {(x, y) for x, y, _ in tiles}
    seen, groups = set(), []
    for start in cells:
        if start in seen:
            continue
        group, stack = [], [start]
        seen.add(start)
        while stack:
            cx, cy = stack.pop()
            group.append((cx, cy))
            for dx in range(-2, 3):
                for dy in range(-2, 3):
                    n = (cx + dx, cy + dy)
                    if n in cells and n not in seen:
                        seen.add(n)
                        stack.append(n)
        groups.append(group)
    keep = [c for g in groups if len(g) >= 0.05 * len(cells) for c in g] or list(cells)
    xs, ys = [c[0] for c in keep], [c[1] for c in keep]
    return min(xs), min(ys), max(xs), max(ys)


def main(zip_path, tga=False):
    with zipfile.ZipFile(zip_path) as z:
        export = json.loads(z.read("export.json"))
        os.makedirs(os.path.join(ADDON, "Data"), exist_ok=True)
        os.makedirs(os.path.join(ADDON, "Overview"), exist_ok=True)
        os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
        with open(os.path.join(ROOT, "data", "export.json"), "w", encoding="utf-8") as f:
            json.dump(export, f, indent=1)
        images = [n for n in z.namelist() if n.startswith("Overview/") and n.endswith(".jpg")]
        for name in images:
            base = os.path.splitext(os.path.basename(name))[0]
            if tga:
                import io
                from PIL import Image
                Image.open(io.BytesIO(z.read(name))).convert("RGB").save(os.path.join(ADDON, "Overview", base + ".tga"))
            else:
                with open(os.path.join(ADDON, "Overview", base + ".jpg"), "wb") as f:
                    f.write(z.read(name))

    lines = [
        "-- Generated by scripts/build_maptiles.py from the MapExplorer export; do not edit by hand.",
        f"-- Source: {export.get('source')}, exported {export.get('exportedAt')}.",
        "-- tiles[y * 64 + x] = minimap FileDataID of ADT tile (x, y); atlases are the bundled overview images.",
        "local _, ns = ...",
        f"ns.OverviewPx = {export['overviewPx']}",
        f'ns.OverviewExt = "{"tga" if tga else "jpg"}"',
        "ns.Maps = {",
    ]
    total = 0
    for m in sorted(export["maps"], key=lambda m: m["id"]):
        lines.append(f"\t[{m['id']}] = {{")
        lines.append(f"\t\tname = {lua_string(m['name'])}, category = {lua_string(m['category'])}, wdt = {m['wdt']},")
        lines.append(f"\t\tminX = {m['minX']}, minY = {m['minY']}, maxX = {m['maxX']}, maxY = {m['maxY']},")
        fx0, fy0, fx1, fy1 = fit_box(m["tiles"])
        lines.append(f"\t\tfitMinX = {fx0}, fitMinY = {fy0}, fitMaxX = {fx1}, fitMaxY = {fy1},")
        lines.append("\t\tatlases = {")
        for a in m["atlases"]:
            lines.append(f"\t\t\t{{ file = {lua_string(a['file'])}, x0 = {a['x0']}, y0 = {a['y0']}, cols = {a['cols']}, rows = {a['rows']}, w = {a['width']}, h = {a['height']} }},")
        lines.append("\t\t},")
        tiles = sorted(m["tiles"], key=lambda t: (t[1], t[0]))
        entries = [f"[{y * 64 + x}]={fdid}" for x, y, fdid in tiles]
        lines.append("\t\ttiles = {")
        for i in range(0, len(entries), 8):
            lines.append("\t\t\t" + ", ".join(entries[i:i + 8]) + ",")
        lines.append("\t\t},")
        lines.append("\t},")
        total += len(tiles)
    lines.append("}")
    out = os.path.join(ADDON, "Data", "MapTiles.lua")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(export['maps'])} maps, {total} tiles, {len(images)} overview images -> {out}")


if __name__ == "__main__":
    main(sys.argv[1], tga="--tga" in sys.argv[2:])
