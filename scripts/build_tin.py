"""Turn a tile mesh from the browser export (northshire_tin.json) into Lua for the GPS3D prototype.

Usage: python scripts/build_tin.py [path/to/northshire_tin.json]
Writes prototypes/GPS3D/Data/Northshire.lua: ns.Tiles["0_32_48"] = { size, minimap, v = {x, height, z, ...},
i = {1-based triangle corners}, w = {per-vertex wall colour r, g, b or -1, -1, -1 on the ground} }.
x runs east and z south in yards from the tile's north-west corner.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def num(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def chunks(items, n=24):
    for i in range(0, len(items), n):
        yield ",".join(items[i:i + n])


def main(src):
    tin = json.load(open(src))
    key = f"{tin['map']}_{tin['tileX']}_{tin['tileY']}"
    v = [num(x) for x in tin["vertices"]]
    i = [str(x + 1) for x in tin["indices"]]
    w = []
    for c in tin["walls"]:
        w += [num(x) for x in c] if c else ["-1", "-1", "-1"]
    out = os.path.join(ROOT, "prototypes", "GPS3D", "Data", "Northshire.lua")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by scripts/build_tin.py from the MapExplorer export; do not edit by hand.\n")
        f.write(f"-- {tin.get('note', '')}\n")
        f.write("local _, ns = ...\nns.Tiles = ns.Tiles or {}\n")
        f.write(f'ns.Tiles["{key}"] = {{ map = {tin["map"]}, tileX = {tin["tileX"]}, tileY = {tin["tileY"]}, size = {tin["tileSize"]!r}, minimap = {tin["minimap"]}, shapeError = {tin["shapeError"]},\n')
        f.write("v = {\n" + ",\n".join(chunks(v)) + "},\n")
        f.write("i = {\n" + ",\n".join(chunks(i, 36)) + "},\n")
        f.write("w = {\n" + ",\n".join(chunks(w)) + "},\n}\n")
    print(f"{key}: {len(tin['vertices']) // 3} vertices, {len(tin['indices']) // 3} triangles -> {out} ({os.path.getsize(out) // 1024} KB)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "data", "northshire_tin.json"))
