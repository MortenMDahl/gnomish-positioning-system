"""Builds prototypes/GPS3D/Data/Lod_<map>.lua: for every tile of the terrain (Data/World_<map>.lua) the
eleven nested meshes GPS3D's ground draws it with (Terrain.lua), from 2048 triangles down to 2 (J8,
2026-10-22).

Usage: python3 scripts/build_terrain_lod.py [prototypes/GPS3D/Data]

Each tile is a right-triangle bintree (scripts/terrain_lod.py): its vertices join the mesh in the order of
how much height error they take off (summed over the grid points they change, and never after a vertex
that depends on them), and level j keeps the first vertices of that order that make at most 2^(11 - j)
triangles. The heights are the ones GPS3D draws (shared edges and corners as both tiles take them).
Per tile with any height difference one string (terrain_lod.encode): per level its triangle count, mean
height error against the grid and the depth of its largest triangles, then each grid point's coarsest
level. Flat tiles get no string (Terrain.lua draws them as the even bintree). Every string is decoded
again and checked: the levels nested and each a valid mesh (every vertex's parents in it, so no cracks
inside the tile), the triangles covering the tile once, the counts within the ladder and as stored, the
errors as stored. Prints sizes and the TOC lines.
"""
import glob
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import terrain_lod as TL  # noqa: E402


def check(c, s, w=None):
    lv, T, E, D = TL.decode_levels(s)
    for j in range(TL.LEVELS):
        act = lv >= j
        for p in np.nonzero(act)[0]:
            for q in TL.DEPS[p]:
                assert act[q], ('parent missing', p, q, j)
        tris = TL.leaves(act)
        assert len(tris) == T[j] <= TL.LEVEL_TRIS[j], ('count', j, len(tris), T[j])
        area = sum(32 * 32 / 2 ** (d + 1) for *_, d in tris)
        assert abs(area - 32 * 32) < 1e-9, ('cover', j, area)
        assert min(t[3] for t in tris) == D[j]
        e = float((np.abs(TL.surface(c, act) - c) * (1 if w is None else w)).mean())  # (weighted as stored)
        assert abs(e - E[j]) <= 1 / 128 + 1e-9, ('error', j, e, E[j])
    assert T[0] == 2048 and T[-1] == 2


UNDER_SHELLS = 0.15  # the weight of a grid point under a city's building shells (2026-10-24): hidden, so it asks for few triangles


def floor_cells(root, mp):
    """the 16.7-yd ground cells under the building shells of every city data addon of map mp (their floor lists)"""
    cells = set()
    for f in glob.glob(os.path.join(root, 'GPS3D_City_*', 'Shells_*.lua')):
        src = open(f).read()
        m = re.search(r'ns\.ShellData\[[^\]]*\] = \{ map = (\d+),', src)
        fl = re.search(r'floor = \{ ([0-9,]*) \}', src)
        if m and int(m.group(1)) == mp and fl and fl.group(1):
            cells.update(int(v) for v in fl.group(1).split(','))
    return cells


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'prototypes', 'GPS3D', 'Data')
    toc, total = [], 0
    for path in sorted(os.listdir(out_dir), key=lambda f: (len(f), f)):
        m = re.match(r'World_(\d+)\.lua$', path)
        if not m:
            continue
        mp = int(m.group(1))
        src = open(os.path.join(out_dir, path)).read()
        world = {int(k): TL.decode(v) for k, v in re.findall(r'\[(\d+)\]="([^"]*)"', src)}
        TL.WEIGHTS.clear()
        cells = floor_cells(os.path.join(out_dir, '..', '..'), mp)
        if cells:
            for key in world:
                tx, ty = key % 64, key // 64
                w = np.ones(TL.NP)
                for p in range(TL.NP):
                    gx, gy = tx * TL.CELLS + p % TL.GRID, ty * TL.CELLS + p // TL.GRID
                    if any((cy * 4096 + cx) in cells for cx in (gx - 1, gx) for cy in (gy - 1, gy)): w[p] = UNDER_SHELLS
                if (w < 1).any(): TL.WEIGHTS[(tx, ty)] = w
            print(f'map {mp}: {len(cells)} ground cells under building shells, {len(TL.WEIGHTS)} tiles weighted {UNDER_SHELLS}')
        lines, flat = [], 0
        for key in sorted(world):
            c = TL.canon(world, key % 64, key // 64)
            extra = TL.edge_errors(world, key % 64, key // 64)
            if np.ptp(c) == 0 and not extra.any():
                flat += 1
                continue
            w = TL.WEIGHTS.get((key % 64, key // 64))
            s = TL.encode(*TL.levels(c, extra, w))
            check(c, s, w)
            lines.append(f'[{key}]="{s}",')
        name = f'Lod_{mp}.lua'
        body = (f'-- Generated by scripts/build_terrain_lod.py from World_{mp}.lua: per tile the levels of its ground mesh\n'
                f'-- ({len(lines)} tiles; {flat} flat tiles have none and are drawn as the even bintree). See Terrain.lua.\n'
                'local _, ns = ...\n'
                'ns.LodData = ns.LodData or {}\n'
                f'ns.LodData[{mp}] = {{\n' + '\n'.join(lines) + '\n}\n')
        open(os.path.join(out_dir, name), 'w', newline='\n').write(body)
        total += len(body)
        toc.append(f'Data\\{name}')
        print(f'{name}: {len(lines)} tiles, {flat} flat, {len(body):,} bytes')
    print(f'total {total:,} bytes')
    print('\n'.join(toc))


if __name__ == '__main__':
    main()
