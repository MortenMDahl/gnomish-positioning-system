"""Turns data/world_heights.json (exported from MapExplorer, see scripts/browser_export_world.js) into
prototypes/GPS3D/Data/World_<map>.lua.

Per tile the export holds one string: a 3-character base (lowest height in half yards + 131072, 18
bits, base64), then 33 x 33 heights, row by row from the north-west corner, 2 characters each (half
yards above the base, 12 bits). The height is the ground or the water surface, whichever is higher.

Usage: python scripts/build_world.py [data/world_heights.json] [prototypes/GPS3D/Data]
Writes one file per map that has terrain (maps whose tiles are all flat are skipped) and prints sizes.
"""
import json, os, sys

B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
VAL = {c: i for i, c in enumerate(B64)}
GRID = 33


def decode(s):
    base = (VAL[s[0]] * 64 + VAL[s[1]]) * 64 + VAL[s[2]] - 131072
    return [(base + VAL[s[3 + i * 2]] * 64 + VAL[s[4 + i * 2]]) * 0.5 for i in range(GRID * GRID)]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'data/world_heights.json'
    out_dir = sys.argv[2] if len(sys.argv) > 2 else 'prototypes/GPS3D/Data'
    data = json.load(open(src))
    written, total_tiles, total_bytes = [], 0, 0
    for map_id, entry in sorted(data['maps'].items(), key=lambda kv: int(kv[0])):
        tiles = entry['tiles']
        if not tiles:
            continue
        # skip maps whose terrain is all flat (instances built only from WMOs)
        flat = all(len(set(decode(s))) == 1 for s in tiles.values())
        if flat:
            print(f'skip {map_id} {entry["name"]}: flat placeholder terrain')
            continue
        for s in tiles.values():
            assert len(s) == 3 + GRID * GRID * 2, (map_id, len(s))
        lines = [
            f'-- Generated by scripts/build_world.py from {os.path.basename(src)} ({data.get("exportedAt", "?")}).',
            f'-- {entry["name"]}: {len(tiles)} tiles, 33 x 33 heights each (see build_world.py for the encoding).',
            'local _, ns = ...',
            'ns.World = ns.World or {}',
            f'ns.World[{int(map_id)}] = {{',
        ]
        for key in sorted(tiles, key=lambda k: (int(k.split('_')[1]), int(k.split('_')[0]))):
            x, y = (int(v) for v in key.split('_'))
            lines.append(f'[{y * 64 + x}]="{tiles[key]}",')
        lines.append('}')
        path = os.path.join(out_dir, f'World_{int(map_id)}.lua')
        text = '\n'.join(lines) + '\n'
        with open(path, 'w', newline='\n') as f:
            f.write(text)
        written.append((int(map_id), entry['name'], len(tiles), len(text)))
        total_tiles += len(tiles)
        total_bytes += len(text)
    for m, name, n, size in written:
        print(f'World_{m}.lua  {name}: {n} tiles, {size / 1024:.0f} KB')
    print(f'{len(written)} maps, {total_tiles} tiles, {total_bytes / 1024 / 1024:.2f} MB')
    # the TOC lines for these files, in map order
    print('TOC:\n' + '\n'.join(f'Data\\World_{m}.lua' for m, *_ in written))


if __name__ == '__main__':
    main()
