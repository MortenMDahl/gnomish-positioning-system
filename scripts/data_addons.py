"""GPS3D's load-on-demand data addons (since 2026-10-22, perf round A5): helpers for build_detail.py and build_models.py.

The buildings (Detail_*.lua) and the game's model placements (Models_*.lua) are not loaded at login with GPS3D:
each group of them is its own addon folder next to GPS3D (prototypes/GPS3D_EK1 ... GPS3D_Models), with
"## LoadOnDemand: 1" in its TOC, which GPS3D's OnDemand.lua loads (C_AddOns.LoadAddOn) when the 3D view first
needs it. A data addon's files get the addon's own namespace from the game, so each folder starts with Link.lua,
which hands its namespace to GPS3D (GPS3D_API.LinkData): what the data files then write into `ns` lands in
GPS3D's namespace, exactly as when GPS3D.toc listed them. The data files themselves are unchanged.
"""
import os
import re

LINK = ('-- Generated by scripts/data_addons.py; do not edit. Hands this data addon\'s namespace to GPS3D (OnDemand.lua):\n'
        '-- the files after it write into GPS3D\'s namespace, as when GPS3D.toc listed them.\n'
        'GPS3D_API.LinkData(select(2, ...))\n')


def gps3d_interface(root):
    """The interface number and version GPS3D.toc gives (the data addons carry the same)."""
    text = open(os.path.join(root, 'GPS3D', 'GPS3D.toc'), encoding='utf-8').read()
    return re.search(r'^## Interface: *(\S+)', text, re.M).group(1), re.search(r'^## Version: *(\S+)', text, re.M).group(1)


def write_addon(root, name, title, notes, files):
    """Writes <root>/<name>/<name>.toc and Link.lua; the data files are written by the caller into the same folder."""
    interface, version = gps3d_interface(root)
    folder = os.path.join(root, name)
    os.makedirs(folder, exist_ok=True)
    toc = '\n'.join([
        f'## Interface: {interface}',
        f'## Title: GPS 3D data: {title}',
        f'## Notes: {notes} Loaded by GPS 3D when its 3D view first needs it (load on demand).',
        f'## Version: {version}',
        '## X-License: MIT',
        '## LoadOnDemand: 1',
        '## Dependencies: GPS3D',
        '',
        'Link.lua',
    ] + list(files)) + '\n'
    with open(os.path.join(folder, name + '.toc'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(toc)
    with open(os.path.join(folder, 'Link.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(LINK)
    return folder


def drop_toc_lines(root, prefix, insert=None, before=None):
    """Removes GPS3D.toc's lines starting with prefix (Data\\Detail_, Data\\Models_), where data files were listed
    before they moved to the data addons; inserts `insert` (a line) where they were, or before `before`, if not there."""
    path = os.path.join(root, 'GPS3D', 'GPS3D.toc')
    lines = open(path, encoding='utf-8').read().split('\n')
    at = next((i for i, l in enumerate(lines) if l.startswith(prefix)), None)
    lines = [l for l in lines if not l.startswith(prefix)]
    if insert and insert not in lines:
        if at is None:
            at = lines.index(before) if before in lines else len(lines)
        lines[at:at] = [insert]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    return path
